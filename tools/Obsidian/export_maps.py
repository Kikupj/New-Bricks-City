"""Export an Obsidian build into the mod: one WAD per map in nbc/maps/, plus their MAPINFO.

    python tools/Obsidian/export_maps.py tools/Obsidian/out/bricks.wad [--prefix NBC_CT] [--limit N]
    python tools/Obsidian/export_maps.py tools/Obsidian/out/roofs.wad --prefix NBC_RF --pair-with NBC_CT --limit 8

--pair-with: a second set for the same districts (the helicopter's rooftop maps): map N goes with district map
N of that prefix, takes its title plus " Rooftops", its MAPINFO goes to nbc/mapinfo/<prefix>_maps.txt and the
pairing to nbc/rooftops.txt; nbc/districts.txt is left alone.

* MAP01, MAP02 ... become nbc/maps/NBC_CT01.wad, NBC_CT02.wad ... (UZDoom names a map after its file).
  Old NBC_CT*.wad files are removed first, so a new build replaces the last one.
* nbc/mapinfo/city_maps.txt: each map's title (from the addon's ZMAPINFO) and CITYSKY; every district exits
  to NBC_HUB. nbc/MAPINFO.txt gets one include line for it (added once).
* nbc/districts.txt: the district pool the raid board reads (map lump, title and environment per line: streets,
  towers, rooftops, industrial, parks, underground or subway, from the addon's "// nbc_env" lines).
* Obsidian's invisible-barrier texture O_INVIST, which the maps use, goes to nbc/textures/obsidian/.
Nothing else from the build (DEHACKED, TITLEPIC, Obsidian's text lumps) is copied.
"""
import argparse
import glob
import os
import re
import struct

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
NBC = os.path.join(ROOT, "nbc")
MAP_LUMPS = {"TEXTMAP", "ZNODES", "REJECT", "BLOCKMAP", "BEHAVIOR", "DIALOGUE", "ENDMAP"}
INCLUDE = 'include "mapinfo/city_maps.txt"   // Obsidian city maps (tools/Obsidian/export_maps.py)'


def read_wad(path):
    data = open(path, "rb").read()
    _, n, off = struct.unpack("<4sii", data[:12])
    for i in range(n):
        pos, size, name = struct.unpack("<ii8s", data[off + 16 * i:off + 16 * i + 16])
        yield name.rstrip(b"\0").decode("ascii", "replace"), data[pos:pos + size]


def write_wad(path, lumps):
    body, directory = b"", b""
    for name, blob in lumps:
        directory += struct.pack("<ii8s", 12 + len(body), len(blob), name.encode("ascii"))
        body += blob
    with open(path, "wb") as f:
        f.write(struct.pack("<4sii", b"PWAD", len(lumps), 12 + len(body)) + body + directory)


def export_pairs(args, maps, rename):
    """A paired set (rooftops): titles from the districts, own MAPINFO file, nbc/rooftops.txt."""
    districts = []
    for line in open(os.path.join(NBC, "districts.txt"), encoding="ascii"):
        m = re.match(r'\s*(\S+)\s+"([^"]*)"', line)
        if m and m.group(1).startswith(args.pair_with):
            districts.append((m.group(1), m.group(2)))
    name = args.prefix.lower() + "_maps.txt"
    info = ["// Generated by tools/Obsidian/export_maps.py --pair-with %s. Don't edit; rebuild." % args.pair_with, ""]
    pairs = ["// The rooftop map for each district (helicopter insertions). Generated by tools/Obsidian/export_maps.py.",
             "// district map, rooftop map"]
    for k, old in enumerate(sorted(maps)):
        new = rename[old]
        dist, title = districts[k] if k < len(districts) else ("", new)
        info += ['map %s "%s Rooftops"' % (new, title.replace('"', "'")), "{", "  levelnum = %d" % (200 + k + 1),
                 '  sky1 = "CITYSKY", 0', '  next = "NBC_HUB"', '  secretnext = "NBC_HUB"', "  nointermission", "}", ""]
        if dist:
            pairs.append("%s %s" % (dist, new))
    with open(os.path.join(NBC, "mapinfo", name), "w", encoding="ascii") as f:
        f.write("\n".join(info))
    with open(os.path.join(NBC, "rooftops.txt"), "w", encoding="ascii") as f:
        f.write("\n".join(pairs) + "\n")
    mapinfo = os.path.join(NBC, "MAPINFO.txt")
    text = open(mapinfo, encoding="utf-8").read()
    inc = 'include "mapinfo/%s"   // rooftop maps for helicopter insertions (export_maps.py --pair-with)' % name
    if "mapinfo/" + name not in text:
        with open(mapinfo, "a", encoding="utf-8") as f:
            f.write(("\n" if not text.endswith("\n") else "") + inc + "\n")
    print("exported %d paired maps; nbc/rooftops.txt, nbc/mapinfo/%s" % (len(maps), name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("wad")
    ap.add_argument("--prefix", default="NBC_CT")
    ap.add_argument("--limit", type=int, default=0, help="export only the first N maps")
    ap.add_argument("--pair-with", default="", help="pair with an exported district set (rooftop maps)")
    args = ap.parse_args()
    assert len(args.prefix) <= 6, "map names are 8 characters: prefix + 2 digits"

    maps, current, zmapinfo, extras = {}, None, None, {}
    for name, blob in read_wad(args.wad):
        if re.fullmatch(r"MAP\d\d", name):
            current = name
            maps[current] = []
        elif current and name in MAP_LUMPS:
            maps[current].append((name, blob))
            if name == "ENDMAP":
                current = None
        else:
            current = None
            if name == "ZMAPINFO":
                zmapinfo = blob.decode("latin1")
            elif name == "O_INVIST":
                extras[name] = blob
    if not maps:
        raise SystemExit("no maps in " + args.wad)
    if args.limit:
        maps = {k: maps[k] for k in sorted(maps)[:args.limit]}

    rename = {old: f"{args.prefix}{int(old[3:]):02d}" for old in maps}
    out_dir = os.path.join(NBC, "maps")
    os.makedirs(out_dir, exist_ok=True)
    for old in glob.glob(os.path.join(out_dir, args.prefix + "*.wad")):
        os.remove(old)
    for old, lumps in maps.items():
        write_wad(os.path.join(out_dir, rename[old] + ".wad"), [(rename[old], b"")] + lumps)
        print(f"{old} -> nbc/maps/{rename[old]}.wad")

    # MAPINFO for the maps: titles from the addon's ZMAPINFO; every district exits back to the hub
    titles = dict(re.findall(r'map\s+(MAP\d\d)\s+"([^"]*)"', zmapinfo or ""))
    envs = dict(re.findall(r'//\s*nbc_env\s+(MAP\d\d)\s+(\w+)', zmapinfo or ""))
    if args.pair_with:
        export_pairs(args, maps, rename)
        return
    info = ["// Generated by tools/Obsidian/export_maps.py from an Obsidian build. Don't edit; rebuild.", ""]
    pool = ["// District pool for the raid board: map lump, title, environment. Generated by tools/Obsidian/export_maps.py.",
            "// Rebuild with tools/Obsidian/make_bricks.ps1; the game assigns gangs to these at the start of a case."]
    for k, old in enumerate(sorted(maps)):
        new, title = rename[old], titles.get(old, rename[old]).replace('"', "'")
        info += ['map %s "%s"' % (new, title), "{", "  levelnum = %d" % (100 + k + 1), '  sky1 = "CITYSKY", 0',
                 '  next = "NBC_HUB"', '  secretnext = "NBC_HUB"', "  nointermission", "}", ""]
        pool.append('%s "%s" %s' % (new, title, envs.get(old, "streets")))
    os.makedirs(os.path.join(NBC, "mapinfo"), exist_ok=True)
    with open(os.path.join(NBC, "mapinfo", "city_maps.txt"), "w", encoding="ascii") as f:
        f.write("\n".join(info))
    with open(os.path.join(NBC, "districts.txt"), "w", encoding="ascii") as f:
        f.write("\n".join(pool) + "\n")

    mapinfo = os.path.join(NBC, "MAPINFO.txt")
    text = open(mapinfo, encoding="utf-8").read()
    if "mapinfo/city_maps.txt" not in text:
        with open(mapinfo, "a", encoding="utf-8") as f:
            f.write(("\n" if not text.endswith("\n") else "") + "\n" + INCLUDE + "\n")
        print("added include line to nbc/MAPINFO.txt")

    if "O_INVIST" in extras:
        tex_dir = os.path.join(NBC, "textures", "obsidian")
        os.makedirs(tex_dir, exist_ok=True)
        with open(os.path.join(tex_dir, "O_INVIST"), "wb") as f:
            f.write(extras["O_INVIST"])

    print(f"exported {len(maps)} maps; play with: +map {rename[min(rename)]}")


if __name__ == "__main__":
    main()
