"""Write docs/corpowars-port-map.md: for each Corpo Wars system PLAN.md ports, its files, the classes it
defines, and every class it uses from OUTSIDE the system (what a port has to bring along, stub or cut).

    python tools/import/corpowars_port_map.py
"""
import collections
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
REF = os.path.join(ROOT, "reference", "corpowars")
OUT = os.path.join(ROOT, "docs", "corpowars-port-map.md")

SYSTEMS = [  # (name, milestone, file stems, what it becomes)
    ("Site kits (level generator)", "M2",
     ["kitgen", "kit_residential", "kit_street", "kit_underground", "procgen", "kitprops", "furniture", "props",
      "stairs", "themes", "decor_apartment", "decor_underground", "building"],
     "NBC_K1/K2/K4 generated floors"),
    ("Navigation graph", "M4, M5", ["nav"], "enemy and ally pathing"),
    ("Guard awareness + UEAI stealth", "M9", ["guard", "main", "stealth", "search", "path", "group"],
     "undercover openers, noise, takedown-and-cuff"),
    ("Civilians", "M9", ["objectives"], "residents, hostages, the escort informant (only CW_Civilian is wanted)"),
    ("Movement", "M11", ["player", "lean"], "mantle (ledge climb), optional lean"),
    ("City map", "M7b", ["citymap", "citymapui", "citysim"], "the Bricks map, dossiers, the gang tick (shape only)"),
    ("Menu framework", "M6-M8", ["terminal"], "CW_UiMenu for the Squad Room, shop, Board, Armory"),
    ("Gear (code only, no weapons)", "M1b, M7", ["gear"],
     "magazine + reserve pattern; CW_Thrown, flashbang and noisemaker gadgets"),
]


def load():
    files = {}
    for d, _, fs in os.walk(os.path.join(REF, "zscript")):
        for f in fs:
            p = os.path.join(d, f)
            files[os.path.relpath(p, REF).replace(os.sep, "/")] = open(p, encoding="latin1").read()
    return files


def main():
    files = load()
    defs, by_file = {}, collections.defaultdict(list)
    for p, t in files.items():
        for m in re.finditer(r"^\s*(extend\s+)?(?:class|struct|mixin\s+class)\s+(\w+)", t, re.M | re.I):
            if not m.group(1):
                defs.setdefault(m.group(2).lower(), (p, m.group(2)))
                by_file[p].append(m.group(2))
    stem = lambda p: os.path.splitext(os.path.basename(p))[0]

    out = ["# Corpo Wars port map",
           "",
           "Generated by `tools/import/corpowars_port_map.py` from `reference/corpowars/zscript/`.",
           "",
           "**How to use it.** When a milestone ports a Corpo Wars system, copy its files from `reference/corpowars/`",
           "into `nbc/zscript/cw/`, include them from `nbc/ZSCRIPT.zs`, and deal with every class in its",
           "*uses from outside* list: bring the class along, replace it with a small NBC version, or cut the code",
           "that needs it. Mission-layer classes (CW_Ledger, CW_City, CW_Contract, CW_Handler's contract parts,",
           "security passes, CW guards in kits) should be **cut or replaced**, not ported (AGENTS.md).",
           "",
           "The systems are tangled: porting all of them as-is would pull in 48 of Corpo Wars' files, including",
           "the city sim and contracts. Only the navigation graph is nearly standalone.",
           ""]
    for name, milestone, stems, becomes in SYSTEMS:
        paths = sorted(p for p in files if stem(p) in stems)
        own = {c.lower() for p in paths for c in by_file[p]}
        uses = collections.defaultdict(set)
        for p in paths:
            for ident in set(re.findall(r"\b([A-Za-z_]\w*)\b", files[p])):
                d = defs.get(ident.lower())
                if d and d[0] not in paths and ident.lower() not in own:
                    uses[d[0]].add(d[1])
        lines = sum(files[p].count("\n") for p in paths)
        out += [f"## {name} ({milestone})", "", f"Becomes: {becomes}. {len(paths)} files, {lines} lines.", "",
                "| File | Lines | Defines |", "|---|---|---|"]
        for p in paths:
            cls = by_file[p]
            shown = ", ".join(cls[:8]) + (f", … ({len(cls)})" if len(cls) > 8 else "")
            out.append(f"| `{p}` | {files[p].count(chr(10))} | {shown} |")
        out += ["", "**Uses from outside the system:**", ""]
        if not uses:
            out.append("- nothing")
        for p, cls in sorted(uses.items()):
            out.append(f"- `{p}`: {', '.join(sorted(cls))}")
        out.append("")

    out += ["## Definition lumps waiting in reference/corpowars/", "",
            "These are **not loaded**. Activate the parts a milestone needs by copying them into nbc/'s own lumps:", "",
            "| File | What's in it | Activate in |", "|---|---|---|",
            "| `modeldef.props.txt` | OBJ prop models → actor classes (models are already in `nbc/models/props/`) | M2, with the kit prop classes |",
            "| `gldefs.txt` | dynamic lights for lamps, city-texture brightmaps (`nbc/brightmaps/city/` already copied), the UEAI stealth shader | M2 (lights, brightmaps), M9 (shader) |",
            "| `shaders/` | the UEAI stealth shader | M9 |",
            "| `sndinfo.txt`, `sndseq.txt` | guard voices, door and gadget sounds, door sequences | M2 (doors), M9 (guards) |",
            "| `cvarinfo.txt`, `keyconf.txt`, `menudef.txt` | CW settings, keys and menus | per system; rename `cw_` to `nbc_` |",
            "| `trnslate.txt` | guard uniform and skin-tone translations | M9 if useful |",
            "| `decorate.vehicles.txt` | parked cars | **already active** (`nbc/actors/cw/vehicles.txt`) |",
            "| `mapinfo.txt`, `zscript.txt`, `decorate.txt` | how Corpo Wars wires everything | reference only |",
            "| `citydist.txt`, `cwcity.txt` | Corpo Wars' city data | reference for `nbc/bricksmap.txt` and `nbc/gangs.txt` (M7b) |",
            "| `civilians2/` | the Civilians2 pack's DECORATE (it **replaces ZombieMan**; never load it as-is) | M9, adapted |",
            "",
            "## Assets already in nbc/ (loaded, unused until wired)", "",
            "- `nbc/textures/cw/` (438 textures), `nbc/sprites/cw/` (decor, signs, cityskyline, breach, gadgets),",
            "  `nbc/models/props/`, `nbc/brightmaps/city/`, `nbc/sounds/cw/breach/`, `nbc/sprites/civilians/`",
            "- `nbc/voxels/` + `nbc/actors/cw/vehicles.txt`: active; there's a parked car in NBC_TEST",
            "- `nbc/maps/NBC_K1.wad`, `NBC_K2.wad`, `NBC_K4.wad`: Corpo Wars' K01, K02, K04 template maps, header lump renamed.",
            "  They still contain Corpo Wars thing numbers (20001+), so loading one before M2 prints unknown-thing errors.",
            "- `tools/cw/`: Corpo Wars' Python tools (genmap.py rebuilds the kit templates; qa/ has map checks)",
            ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
