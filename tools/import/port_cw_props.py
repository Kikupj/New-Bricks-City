"""Port Corpo Wars' furniture, kit props and decor sprites into the mod as placeable map things.

    python tools/import/port_cw_props.py

* Copies furniture.zs, kitprops.zs and the bank/apartment/underground/industrial decor sets from
  reference/corpowars/zscript/corpowars/ into nbc/zscript/cw/ (unchanged except lines marked "// NBC:").
* nbc/MODELDEF.txt: the Corpo Wars model definitions for the ported classes only.
* nbc/sprites/cw/models/CWMDA0.png: the 1x1 placeholder sprite the models hang on.
* nbc/mapinfo/cw_props.txt: DoomEdNums for every ported class, furniture from 26200 and decor from
  26400 (in file order, so numbers are stable), included from nbc/MAPINFO.txt.
* Adds the include lines to nbc/ZSCRIPT.zs and nbc/MAPINFO.txt once.
Safe to re-run: it rewrites only the files listed above.
"""
import os
import re
import shutil

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
REF = os.path.join(ROOT, "reference", "corpowars")
SRC = os.path.join(REF, "zscript", "corpowars")
NBC = os.path.join(ROOT, "nbc")
CW_SPRITES = r"C:\Games\Corpo Wars\CorpoWars\sprites"

FURNITURE_FILES = ["furniture.zs", "kitprops.zs"]
DECOR_FILES = ["decor_bank.zs", "decor_apartment.zs", "decor_underground.zs", "decor_industrial.zs"]
FURNITURE_BASE, DECOR_BASE = 26200, 26400

# Wall sprites placed from a map land at floor height; Corpo Wars always spawned them at a height.
LIFT = """class CWD_Wall : Actor { Default { +NOGRAVITY; +NOBLOCKMAP; +WALLSPRITE; +DONTSPLASH; Radius 2; Height 8; }
	// NBC: placed as a map thing (Obsidian room prefabs) it starts on the floor; lift it to wall height.
	override void PostBeginPlay() { Super.PostBeginPlay(); if (pos.z <= floorz + 1) SetZ(floorz + 44); }
}"""


def classes(path):
    out = []
    for m in re.finditer(r"^class\s+(\w+)\s*:\s*(\w+)", open(path, encoding="latin1").read(), re.M):
        out.append((m.group(1), m.group(2)))
    return out


def ensure_line(path, needle, line):
    text = open(path, encoding="utf-8").read()
    if needle not in text:
        with open(path, "a", encoding="utf-8") as f:
            f.write(("" if text.endswith("\n") else "\n") + line + "\n")
        print("added to", os.path.relpath(path, ROOT) + ":", line)


def main():
    dst = os.path.join(NBC, "zscript", "cw")
    os.makedirs(dst, exist_ok=True)
    for name in FURNITURE_FILES + DECOR_FILES:
        text = open(os.path.join(SRC, name), encoding="latin1").read()
        if name == "decor_bank.zs":
            old = "class CWD_Wall : Actor { Default { +NOGRAVITY; +NOBLOCKMAP; +WALLSPRITE; +DONTSPLASH; Radius 2; Height 8; } }"
            assert old in text
            text = text.replace(old, LIFT)
        with open(os.path.join(dst, name), "w", encoding="latin1") as f:
            f.write("// Ported from Corpo Wars (reference/corpowars/zscript/corpowars/%s) by tools/import/port_cw_props.py.\n" % name)
            f.write(text)

    # map numbers
    furniture = [c for n in FURNITURE_FILES for c, base in classes(os.path.join(SRC, n))
                 if c.startswith("CW_F") and c not in ("CW_Furniture",)]
    decor = [c for n in DECOR_FILES for c, base in classes(os.path.join(SRC, n)) if c.startswith("CWD_")
             and c not in ("CWD_Wall", "CWD_Stand")]
    lines = ["// Generated by tools/import/port_cw_props.py: map numbers for the ported Corpo Wars props.",
             "// Furniture and kit props 26200+, decor sprites 26400+. Used by the Obsidian room prefabs.",
             "DoomEdNums", "{"]
    for i, c in enumerate(furniture):
        lines.append(f"\t{FURNITURE_BASE + i} = {c}")
    for i, c in enumerate(decor):
        lines.append(f"\t{DECOR_BASE + i} = {c}")
    lines.append("}")
    assert FURNITURE_BASE + len(furniture) <= DECOR_BASE and DECOR_BASE + len(decor) < 27000
    os.makedirs(os.path.join(NBC, "mapinfo"), exist_ok=True)
    with open(os.path.join(NBC, "mapinfo", "cw_props.txt"), "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")

    # models for the ported classes only
    mdl = open(os.path.join(REF, "modeldef.props.txt"), encoding="latin1").read()
    keep = set(furniture)
    blocks = re.split(r"(?=^Model\s)", mdl, flags=re.M)
    out = ["// Ported from Corpo Wars' modeldef.props.txt by tools/import/port_cw_props.py (ported classes only).\n\n"]
    for b in blocks:
        m = re.match(r"Model\s+(\w+)", b)
        if m and m.group(1) in keep:
            out.append(b.rstrip() + "\n\n")
    with open(os.path.join(NBC, "MODELDEF.txt"), "w", encoding="latin1") as f:
        f.write("".join(out))

    os.makedirs(os.path.join(NBC, "sprites", "cw", "models"), exist_ok=True)
    shutil.copy2(os.path.join(CW_SPRITES, "CWMDA0.png"), os.path.join(NBC, "sprites", "cw", "models", "CWMDA0.png"))

    inc = "\n// Corpo Wars props and decor, placeable map things (tools/import/port_cw_props.py)\n" + \
          "\n".join(f'#include "zscript/cw/{n}"' for n in FURNITURE_FILES + DECOR_FILES)
    ensure_line(os.path.join(NBC, "ZSCRIPT.zs"), "zscript/cw/furniture.zs", inc)
    ensure_line(os.path.join(NBC, "MAPINFO.txt"), "mapinfo/cw_props.txt",
                'include "mapinfo/cw_props.txt"   // Corpo Wars prop map numbers (tools/import/port_cw_props.py)')
    print(f"ported {len(furniture)} furniture/props ({FURNITURE_BASE}-{FURNITURE_BASE + len(furniture) - 1}), "
          f"{len(decor)} decor sprites ({DECOR_BASE}-{DECOR_BASE + len(decor) - 1}), {len(out) - 1} models")


if __name__ == "__main__":
    main()
