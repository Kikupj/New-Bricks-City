# Corpo Wars: list every wall/flat texture in the mod for the Obsidian addon (CORPOWARS.OURS), so the
# generator knows which textures are ours and swaps everything else. Re-run after adding textures:
#   python obsidian_textures.py        (writes obsidian_addon/CorpoWars/modules/corpowars_textures.lua)
import os
HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.join(HERE, "..", "CorpoWars", "textures")
OUT = os.path.join(HERE, "obsidian_addon", "CorpoWars", "modules", "corpowars_textures.lua")

def main():
    names = []
    for sub in ("", "themes"):          # props/ are model skins, not for walls
        d = os.path.join(TEX, sub)
        names += [f[:-4].upper() for f in os.listdir(d) if f.lower().endswith(".png")]
    names = sorted(set(names))
    out = ["-- Generated by CorpoWars_tools/obsidian_textures.py: every Corpo Wars wall/flat texture (props excluded).",
           "CORPOWARS = CORPOWARS or {}", "CORPOWARS.OURS =", "{"]
    line = "  "
    for n in names:
        item = n + "=1, "
        if len(line) + len(item) > 110: out.append(line.rstrip()); line = "  "
        line += item
    out.append(line.rstrip()); out.append("}")
    open(OUT, "w").write("\n".join(out) + "\n")
    print(len(names), "textures ->", OUT)

if __name__ == "__main__": main()
